import type { Doc } from "@faber/shared";
import { docTypeLabel } from "./format";

/**
 * Pure logic for the toolbar icon: is the current tab saved in Faber?
 * The background worker feeds in what it learned from GET /api/docs/lookup and
 * applies the resulting icon + title with chrome.action.setIcon/setTitle.
 */

export type IconState = "saved" | "pinned" | "unsaved" | "unknown";

/** Outcome of looking a tab's URL up in the daemon. */
export type LookupResult =
  | { kind: "doc"; doc: Doc }
  | { kind: "missing" }
  | { kind: "offline" }
  | { kind: "unpaired" }
  /** The extension can't see this tab's address (no host permission and "tabs" not granted). */
  | { kind: "no-access" }
  /** Not a web page (chrome://, file:, the daemon's own UI, incognito…). */
  | { kind: "not-web" };

export interface TabStatus {
  state: IconState;
  title: string;
}

export function statusFor(r: LookupResult): TabStatus {
  switch (r.kind) {
    case "doc": {
      const d = r.doc;
      const parts = [`Saved in Faber`, `opened ${d.visit_count}×`];
      if (d.enrichment) parts.push(docTypeLabel(d.enrichment.doc_type));
      if (d.pinned) parts.push("Pinned");
      return { state: d.pinned ? "pinned" : "saved", title: parts.join(" · ") };
    }
    case "missing":
      return { state: "unsaved", title: "Not saved — click to save" };
    case "offline":
      return { state: "unknown", title: "Faber — daemon offline" };
    case "unpaired":
      return { state: "unknown", title: "Faber — needs approval in the app" };
    case "no-access":
      return { state: "unknown", title: "Faber — turn on “Show saved status on every site” in Options to see if this page is saved" };
    case "not-web":
      return { state: "unknown", title: "Faber" };
  }
}

/** Toolbar icon files per state (16px and 32px for HiDPI), generated by scripts/brand.ts (`bun run brand`). */
export function iconPaths(state: IconState): Record<"16" | "32", string> {
  return { "16": `icons/action-${state}-16.png`, "32": `icons/action-${state}-32.png` };
}

/** Only real web pages are ever looked up. */
export function isLookupUrl(url: string | undefined): url is string {
  if (!url) return false;
  try {
    const u = new URL(url);
    return u.protocol === "http:" || u.protocol === "https:";
  } catch {
    return false;
  }
}

/**
 * Short-lived cache of lookups keyed by canonical URL, with in-flight
 * de-duplication so tab switches and repeated events don't hammer the daemon.
 * Only definite answers (doc / missing) are cached; offline/unpaired are retried.
 */
export class LookupCache {
  private entries = new Map<string, { at: number; result: LookupResult }>();
  private inflight = new Map<string, Promise<LookupResult>>();

  constructor(
    private ttlMs = 30_000,
    private now: () => number = Date.now,
  ) {}

  get(key: string, fetcher: () => Promise<LookupResult>): Promise<LookupResult> {
    const hit = this.entries.get(key);
    if (hit && this.now() - hit.at < this.ttlMs) return Promise.resolve(hit.result);
    const pending = this.inflight.get(key);
    if (pending) return pending;
    const p = fetcher()
      .then((result) => {
        if (result.kind === "doc" || result.kind === "missing") this.entries.set(key, { at: this.now(), result });
        else this.entries.delete(key);
        return result;
      })
      .finally(() => this.inflight.delete(key));
    this.inflight.set(key, p);
    return p;
  }

  invalidate(key: string) {
    this.entries.delete(key);
  }

  clear() {
    this.entries.clear();
  }
}
