/** Pieces of the release build that are worth testing on their own (scripts/release.test.ts). */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const TARGETS = ["darwin-arm64", "darwin-x64", "linux-x64", "linux-arm64"] as const;
export type Target = (typeof TARGETS)[number];

const VERSION_TS = "packages/daemon/src/version.ts";
// Plain x.y.z only: Chrome rejects anything else as an extension version.
const SEMVER = /^\d+\.\d+\.\d+$/;

function packageJsons(root: string): string[] {
  return ["package.json", ...readdirSync(join(root, "packages")).map((p) => join("packages", p, "package.json"))].filter((p) => {
    try {
      readFileSync(join(root, p));
      return true;
    } catch {
      return false;
    }
  });
}

/** Every place the version is written down, and what each says. */
export function versionsIn(root: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const p of packageJsons(root)) out[p] = (JSON.parse(readFileSync(join(root, p), "utf8")) as { version: string }).version;
  out[VERSION_TS] = /VERSION = "([^"]+)"/.exec(readFileSync(join(root, VERSION_TS), "utf8"))?.[1] ?? "(missing)";
  return out;
}

/** The version, after checking every package agrees on it. */
export function checkVersions(root: string): string {
  const all = versionsIn(root);
  const distinct = [...new Set(Object.values(all))];
  if (distinct.length !== 1) {
    throw new Error(`Versions disagree:\n${Object.entries(all).map(([f, v]) => `  ${v}  ${f}`).join("\n")}\nFix with: bun scripts/version.ts <x.y.z>`);
  }
  const v = distinct[0]!;
  if (!SEMVER.test(v)) throw new Error(`"${v}" isn't a version like 1.2.3`);
  return v;
}

/** Write `version` everywhere checkVersions looks. */
export function setVersion(root: string, version: string) {
  if (!SEMVER.test(version)) throw new Error(`"${version}" isn't a version like 1.2.3`);
  for (const p of packageJsons(root)) {
    const path = join(root, p);
    const text = readFileSync(path, "utf8");
    writeFileSync(path, text.replace(/"version": "[^"]+"/, `"version": "${version}"`));
  }
  const ts = join(root, VERSION_TS);
  writeFileSync(ts, readFileSync(ts, "utf8").replace(/VERSION = "[^"]+"/, `VERSION = "${version}"`));
}

const block = (indent: string, target: Target, baseUrl: string, version: string, sha: string | undefined) =>
  sha
    ? `${indent}url "${baseUrl}/faber-${version}-${target}.tar.gz"\n${indent}sha256 "${sha}"`
    : null;

/** The Homebrew formula for one release. Platforms without a sha are left out. */
export function renderFormula(o: { version: string; baseUrl: string; shas: Partial<Record<Target, string>> }): string {
  const section = (os: "macos" | "linux", arm: Target, intel: Target) => {
    const a = block("      ", arm, o.baseUrl, o.version, o.shas[arm]);
    const i = block("      ", intel, o.baseUrl, o.version, o.shas[intel]);
    if (!a && !i) return null;
    return [`  on_${os} do`, a && `    on_arm do\n${a}\n    end`, i && `    on_intel do\n${i}\n    end`, "  end"].filter(Boolean).join("\n");
  };
  const platforms = [section("macos", "darwin-arm64", "darwin-x64"), section("linux", "linux-arm64", "linux-x64")].filter(Boolean);
  if (!platforms.length) throw new Error("no platforms to put in the formula");
  return `# Generated by scripts/release.ts in github.com/asweeney86/faber for v${o.version}. Don't edit by hand.
class Faber < Formula
  desc "Local-first, AI-enriched memory for the documents you open at work"
  homepage "https://github.com/asweeney86/faber"
  version "${o.version}"
  license "Apache-2.0"

${platforms.join("\n\n")}

  def install
    bin.install "bin/faber"
    # The Chrome extension and (on macOS) the launcher app. \`faber setup\` copies them
    # to stable places (~/.faber/extension, ~/Applications), and the daemon keeps those
    # copies up to date after every upgrade.
    pkgshare.install Dir["share/faber/*"]
  end

  service do
    run [opt_bin/"faber", "serve"]
    environment_variables FABER_SERVICE: "1", PATH: std_service_path_env
    # Restart after a crash, or when the daemon exits to pick up an upgrade.
    keep_alive successful_exit: false
    process_type :background
    log_path var/"log/faber.log"
    error_log_path var/"log/faber.log"
  end

  def caveats
    <<~EOS
      Finish setting up (local AI models, background service, Chrome extension, launcher):
        faber setup
    EOS
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/faber version").strip
    ENV["FABER_HOME"] = testpath/"home"
    system bin/"faber", "status"
    assert_path_exists testpath/"home/faber.sqlite"
  end
end
`;
}

/** The version after `current`: "patch", "minor", "major", or an explicit x.y.z (which must be newer). */
export function nextVersion(current: string, bump: string): string {
  if (!SEMVER.test(current)) throw new Error(`"${current}" isn't a version like 1.2.3`);
  const [maj, min, pat] = current.split(".").map(Number) as [number, number, number];
  let next: string;
  if (bump === "patch") next = `${maj}.${min}.${pat + 1}`;
  else if (bump === "minor") next = `${maj}.${min + 1}.0`;
  else if (bump === "major") next = `${maj + 1}.0.0`;
  else next = bump.replace(/^v/, "");
  if (!SEMVER.test(next)) throw new Error(`"${bump}" isn't patch, minor, major or a version like 1.2.3`);
  const cmp = next.split(".").map(Number).reduce((acc, n, i) => acc || n - [maj, min, pat][i]!, 0);
  if (cmp <= 0) throw new Error(`${next} isn't newer than ${current}`);
  return next;
}

/** Release notes from the commit subjects since the last release: one bullet each, PR numbers and earlier "Release" commits dropped. */
export function releaseNotes(subjects: string[]): string[] {
  return subjects
    .map((s) => s.trim().replace(/\s*\(#\d+\)$/, ""))
    .filter((s) => s && !/^Release \d+\.\d+\.\d+$/.test(s))
    .map((s) => `- ${s}`);
}
